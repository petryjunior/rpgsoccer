/**
 * @param {string} selecaoId
 * @returns {{ prenomes: string[], sobrenomes: string[] }}
 */
export function listasNomesCampanha(selecaoId) {
  const id = String(selecaoId || "").toLowerCase();
  const t = TABELAS[id] ?? TABELAS.ale;
  if (t.prenomes.length * t.sobrenomes.length < 120) {
    return { prenomes: TABELAS.ale.prenomes, sobrenomes: TABELAS.ale.sobrenomes };
  }
  return { prenomes: t.prenomes, sobrenomes: t.sobrenomes };
}

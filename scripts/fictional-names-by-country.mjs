function namesForTeam(id) {
  const pool = POOLS[id];
  if (!pool) {
    throw new Error(`Sem pool de nomes para id: ${id}`);
  }
  const { first, last } = pool;
  const pairs = [];
  for (const f of first) {
    for (const l of last) {
      pairs.push(`${f} ${l}`);
    }
  }
  let seed = id.split("").reduce((a, c) => a + c.charCodeAt(0), 0);
  /** @returns {number} 0..1 */
  function rnd() {
    seed = (Math.imul(seed, 1103515245) + 12345) >>> 0;
    return seed / 4294967296;
  }
  for (let i = pairs.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [pairs[i], pairs[j]] = [pairs[j], pairs[i]];
  }
  return pairs.slice(0, 22);
}

const lines = readFileSync(path, "utf8").split("\n");
let currentId = null;
/** @type {string[]} */
let queue = [];
let qi = 0;

const out = lines.map((line) => {
  const idm = line.match(/^\s*id:\s*"([a-z0-9]+)"/);
  if (idm) {
    currentId = idm[1];
    queue = namesForTeam(currentId);
    qi = 0;
  }
  return line.replace(/j\("[^"]*",/g, () => {
    const name = queue[qi] ?? "Nome Sobrenome";
    qi++;
    return `j("${name}",`;
  });
});

writeFileSync(path, out.join("\n"), "utf8");
